#!/usr/bin/env bash
#
# Idempotent production-env generator + age encryptor (secrets-management.md,
# invoked by `make deploy-init` / `make deploy-test-init` INSIDE the dev
# container, which provides PHP for key generation and the age CLI).
#
# Usage: init.sh [env_local] [env_age] [production|vm-test]
#   defaults: .env.prod.local .env.prod.age production
#   vm-test:  .env.prod.test.local .env.prod.test.age vm-test
#
# Behavior:
#   1. If the plaintext env file does not exist — create it from the profile
#      template (devops.md "Production .env Overrides" table): static values,
#      generated secrets, CHANGE_ME placeholders for admin-supplied keys.
#   2. If it exists — never overwrite any existing value: only fill keys that
#      are missing, empty, or still the CHANGE_ME placeholder. Never
#      regenerates an existing secret. APP_URL and GITHUB_REDIRECT_URI are
#      derived from DOMAIN on every run (the single admin-editable source).
#      The vm-test profile fills its own safe dummies for the GitHub/mail keys
#      and logs mail instead of calling the API; DOMAIN stays gated.
#   3. Validation gate — refuse to encrypt while any admin-supplied key
#      (DOMAIN, LETSENCRYPT_EMAIL, GITHUB_CLIENT_ID, GITHUB_CLIENT_SECRET,
#      MAIL_API_ENDPOINT, MAIL_API_TOKEN, MAIL_FROM_ADDRESS) is empty or a
#      CHANGE_ME placeholder: print the missing keys and exit non-zero.
#   4. Encrypt: age -r "$(cat devops/secrets/age.pub)" -o <env_age> <env_local>
#   5. Round-trip verify when the private key is available (AGE_PRIVATE_KEY
#      env var, or on the first run while devops/secrets/age-identity.txt
#      still exists): decrypt the encrypted file to a temp file and compare it
#      byte-for-byte. The playbook's first deploy verifies implicitly
#      otherwise (a failed decrypt aborts the deploy).
#
# The script NEVER prints secret values.
#
# IMPORTANT: the values written into the env file must stay safe to
# `set -a; . file` on the server (the deploy sources it before docker build
# and envsubst): no spaces, quotes, backslashes or shell metacharacters.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT"

ENV_LOCAL="$ROOT/${1:-.env.prod.local}"
ENV_AGE="$ROOT/${2:-.env.prod.age}"
PROFILE="${3:-production}"

case "$PROFILE" in
    production) INIT_TARGET="make deploy-init" ;;
    vm-test)    INIT_TARGET="make deploy-test-init" ;;
    *)
        echo "usage: init.sh [env_local] [env_age] [production|vm-test]" >&2
        exit 2
        ;;
esac

PUB="$ROOT/devops/secrets/age.pub"
IDENTITY="$ROOT/devops/secrets/age-identity.txt"

# --- generated-secret commands (PHP is provided by the dev container) ---
gen_hex32()  { php -r 'echo bin2hex(random_bytes(32));'; }
gen_hex16()  { php -r 'echo bin2hex(random_bytes(16));'; }
gen_b64_32() { php -r 'echo base64_encode(random_bytes(32));'; }
gen_app_key() { php artisan key:generate --show 2>/dev/null; }

# Admin-supplied keys required before the first deploy (validation gate).
ADMIN_KEYS=(
    DOMAIN
    LETSENCRYPT_EMAIL
    GITHUB_CLIENT_ID
    GITHUB_CLIENT_SECRET
    MAIL_API_ENDPOINT
    MAIL_API_TOKEN
    MAIL_FROM_ADDRESS
)

# Canonical emission order. Entries starting with '#' are emitted verbatim
# as comments; everything else is a KEY whose value is resolved by
# resolve_value() (existing values preserved, missing/placeholder filled).
ORDER=(
    "# ────────────────────────────────────────────────────────────────────"
    "# Deployment environment ($(basename "$ENV_LOCAL")) — generated by"
    "# $INIT_TARGET."
    "# Work file only: encrypted to the matching .age file (gitignored), decrypted"
    "# on the server into the profile env by the first deploy."
    "#"
    "# Key reference: devops.md \"Production .env Overrides\" (prod values differ"
    "# from the dev .env.example); the deploy sources this file on the server, so"
    "# values must remain shell-safe KEY=VALUE lines (no spaces, quotes or"
    "# shell metacharacters)."
    "# ────────────────────────────────────────────────────────────────────"
    APP_NAME
    APP_ENV
    APP_DEBUG
    "# APP_URL is derived from DOMAIN on every run — edit DOMAIN, not APP_URL."
    APP_URL
    "# TRUSTED_PROXIES stays empty: nginx terminates TLS itself in production"
    "# and spoofed X-Forwarded-* headers must stay ignored."
    TRUSTED_PROXIES
    CACHE_STORE
    SESSION_DRIVER
    SESSION_SECURE_COOKIE
    QUEUE_CONNECTION
    INERTIA_SSR_URL
    INERTIA_SSR_ENSURE_BUNDLE_EXISTS
    PUBLIC_PAGE_CACHE_ENABLED
    PUBLIC_PAGE_CACHE_TTL
    "# ── Admin-supplied — fill before the first deploy (validation gate) ──"
    "# DOMAIN: the public domain, no scheme (e.g. example.com). Also feeds the"
    "# nginx entrypoint <domain> placeholders and the Let's Encrypt cert path."
    DOMAIN
    "# LETSENCRYPT_EMAIL: Let's Encrypt certificate expiry notifications."
    LETSENCRYPT_EMAIL
    "# ── Database ──"
    DB_CONNECTION
    DB_HOST
    DB_PORT
    DB_DATABASE
    DB_USERNAME
    DB_PASSWORD
    "# ── Redis (cache + queues + sessions) ──"
    REDIS_HOST
    REDIS_PORT
    REDIS_PASSWORD
    "# ── RustFS object storage (public assets bucket + private backups) ──"
    RUSTFS_ACCESS_KEY
    RUSTFS_SECRET_KEY
    RUSTFS_BUCKET
    RUSTFS_BACKUPS_ACCESS_KEY
    RUSTFS_BACKUPS_SECRET_KEY
    RUSTFS_BACKUPS_BUCKET
    RUSTFS_ENDPOINT
    RUSTFS_USE_PATH_STYLE_ENDPOINT
    "# ANALYTICS_IP_HASH_KEY: per-environment HMAC key for visitor hashing —"
    "# must NOT equal APP_KEY (cross-environment correlation prevention)."
    ANALYTICS_IP_HASH_KEY
    "# BACKUP_ENCRYPTION_KEY: legacy fallback only — new backups use the"
    "# DB-managed keys from backup_encryption_keys. Set once, store offline."
    BACKUP_ENCRYPTION_ENABLED
    BACKUP_ENCRYPTION_KEY
    "# ── Mail (api transport — env defaults, overridable via admin Settings) ──"
    MAIL_MAILER
    MAIL_API_ENDPOINT
    MAIL_API_TOKEN
    MAIL_FROM_ADDRESS
    MAIL_FROM_NAME
    "# ── GitHub OAuth ──"
    "# GITHUB_CLIENT_ID: from the registered GitHub OAuth app (production"
    "# callback URL). GITHUB_CLIENT_SECRET starts as a RANDOM PLACEHOLDER —"
    "# replace it with the real client secret from the OAuth app before the"
    "# first deploy (the validation gate cannot tell them apart)."
    GITHUB_CLIENT_ID
    GITHUB_CLIENT_SECRET
    "# GITHUB_REDIRECT_URI is derived from DOMAIN on every run."
    GITHUB_REDIRECT_URI
    "# ── Laravel ──"
    "# APP_KEY: encrypts Crypt data (TOTP secrets, GitHub tokens, backup"
    "# encryption keys at rest). Generated once — regenerating it would make"
    "# the stored ciphertexts undecryptable."
    APP_KEY
)

log() { printf '[deploy-init] %s\n' "$*"; }
die() { log "ERROR: $*" >&2; exit 1; }

declare -A CUR=()

read_current_env() {
    local line key val
    CUR=()
    [ -f "$ENV_LOCAL" ] || return 0
    while IFS= read -r line || [ -n "$line" ]; do
        case "$line" in '' | \#*) continue ;; esac
        key="${line%%=*}"
        val="${line#*=}"
        case "$key" in
            *[!A-Za-z0-9_]* | '') continue ;;
        esac
        CUR["$key"]="$val"
    done < "$ENV_LOCAL"
}

# Resolve the value a key should carry in the (re)generated file.
resolve_value() {
    local key="$1"
    local current="${CUR[$key]:-}"
    local domain="${CUR[DOMAIN]:-CHANGE_ME}"
    local base="https://${domain}"

    case "$key" in
        APP_URL)
            [ "$domain" = "CHANGE_ME" ] && base="https://CHANGE_ME"
            printf '%s' "$base"
            return
            ;;
        GITHUB_REDIRECT_URI)
            [ "$domain" = "CHANGE_ME" ] && base="https://CHANGE_ME"
            printf '%s/admin/login/github/callback' "$base"
            return
            ;;
    esac

    # Existing, filled-in values are never overwritten.
    if [ -n "$current" ] && [ "$current" != "CHANGE_ME" ]; then
        printf '%s' "$current"
        return
    fi

    # Test profile: mail is logged locally and the GitHub OAuth keys are
    # dummies; DOMAIN stays CHANGE_ME so the validation gate still requires
    # the operator to set the certificate hostname.
    if [ "$PROFILE" = "vm-test" ]; then
        case "$key" in
            LETSENCRYPT_EMAIL)    printf '%s' 'vm-test@example.invalid'; return ;;
            GITHUB_CLIENT_ID)     printf '%s' 'vm-test'; return ;;
            GITHUB_CLIENT_SECRET) printf '%s' 'vm-test'; return ;;
            MAIL_MAILER)          printf '%s' 'log'; return ;;
            MAIL_API_ENDPOINT)    printf '%s' 'http://127.0.0.1:9/api'; return ;;
            MAIL_API_TOKEN)       printf '%s' 'vm-test'; return ;;
            MAIL_FROM_ADDRESS)    printf '%s' 'vm-test@example.invalid'; return ;;
        esac
    fi

    case "$key" in
        # Static template values (devops.md "Production .env Overrides").
        APP_NAME)                         printf '%s' 'Portfolio' ;;
        APP_ENV)                          printf '%s' 'production' ;;
        APP_DEBUG)                        printf '%s' 'false' ;;
        TRUSTED_PROXIES)                  printf '%s' '' ;;
        CACHE_STORE)                      printf '%s' 'redis' ;;
        SESSION_DRIVER)                   printf '%s' 'redis' ;;
        SESSION_SECURE_COOKIE)            printf '%s' 'true' ;;
        QUEUE_CONNECTION)                 printf '%s' 'redis' ;;
        INERTIA_SSR_URL)                  printf '%s' 'http://node:3000' ;;
        # The PHP image ships no SSR bundle (only the node image does), so the
        # bundle probe would silently disable SSR in every deployed container.
        INERTIA_SSR_ENSURE_BUNDLE_EXISTS) printf '%s' 'false' ;;
        PUBLIC_PAGE_CACHE_ENABLED)        printf '%s' 'true' ;;
        PUBLIC_PAGE_CACHE_TTL)            printf '%s' '300' ;;
        DB_CONNECTION)                    printf '%s' 'pgsql' ;;
        DB_HOST)                          printf '%s' 'db' ;;
        DB_PORT)                          printf '%s' '5432' ;;
        DB_DATABASE)                      printf '%s' 'portfolio' ;;
        DB_USERNAME)                      printf '%s' 'portfolio' ;;
        REDIS_HOST)                       printf '%s' 'redis' ;;
        REDIS_PORT)                       printf '%s' '6379' ;;
        RUSTFS_BUCKET)                    printf '%s' 'portfolio' ;;
        RUSTFS_BACKUPS_BUCKET)            printf '%s' 'backups' ;;
        RUSTFS_ENDPOINT)                  printf '%s' 'http://rustfs:9000' ;;
        RUSTFS_USE_PATH_STYLE_ENDPOINT)   printf '%s' 'true' ;;
        BACKUP_ENCRYPTION_ENABLED)        printf '%s' 'true' ;;
        MAIL_MAILER)                      printf '%s' 'api' ;;
        MAIL_FROM_NAME)                   printf '%s' 'Portfolio' ;;
        # Generated secrets (never regenerated once written).
        APP_KEY)                          gen_app_key ;;
        GITHUB_CLIENT_SECRET)             gen_hex32 ;;
        DB_PASSWORD | REDIS_PASSWORD)     gen_hex32 ;;
        RUSTFS_SECRET_KEY | RUSTFS_BACKUPS_SECRET_KEY)   gen_hex32 ;;
        RUSTFS_ACCESS_KEY | RUSTFS_BACKUPS_ACCESS_KEY)   gen_hex16 ;;
        ANALYTICS_IP_HASH_KEY)            gen_hex32 ;;
        BACKUP_ENCRYPTION_KEY)            gen_b64_32 ;;
        # Admin-supplied keys start as CHANGE_ME (validation gate).
        *) printf '%s' 'CHANGE_ME' ;;
    esac
}

write_env_file() {
    local tmp
    tmp="$(mktemp "$ENV_LOCAL.XXXXXX")"
    {
        local token key
        for token in "${ORDER[@]}"; do
            case "$token" in
                \#*) printf '%s\n' "$token" ;;
                *)
                    key="$token"
                    printf '%s=%s\n' "$key" "$(resolve_value "$key")"
                    ;;
            esac
        done
    } > "$tmp"
    chmod 600 "$tmp"
    mv -f "$tmp" "$ENV_LOCAL"
    chmod 600 "$ENV_LOCAL"
}

run_validation_gate() {
    local missing=() key val
    for key in "${ADMIN_KEYS[@]}"; do
        val="${CUR[$key]:-}"
        if [ -z "$val" ] || [ "$val" = "CHANGE_ME" ]; then
            missing+=("$key")
        fi
    done
    if [ "${#missing[@]}" -gt 0 ]; then
        log "refusing to encrypt — fill these keys in $ENV_LOCAL first:"
        printf '  %s\n' "${missing[@]}"
        log "(then re-run: $INIT_TARGET; existing values are never overwritten)"
        exit 1
    fi
}

# ---------------------------------------------------------------- main
if [ ! -f "$PUB" ]; then
    die "missing $PUB — bootstrap the age keypair first: age-keygen -o devops/secrets/age-identity.txt (see secrets-management.md)"
fi

read_current_env
write_env_file
read_current_env

run_validation_gate

log "encrypting $(basename "$ENV_LOCAL") -> $(basename "$ENV_AGE")"
age -r "$(cat "$PUB")" -o "$ENV_AGE" "$ENV_LOCAL"
chmod 600 "$ENV_AGE"

# --- round-trip verification (best effort, never prints values) ---------
ROUND_TRIP_VERIFIED=0
if [ -n "${AGE_PRIVATE_KEY:-}" ]; then
    keytmp="$(mktemp)"
    outtmp="$(mktemp)"
    chmod 600 "$keytmp"
    trap 'rm -f "$keytmp" "$outtmp"' EXIT
    printf '%s\n' "$AGE_PRIVATE_KEY" > "$keytmp"
    if age -d -i "$keytmp" -o "$outtmp" "$ENV_AGE" 2>/dev/null && cmp -s "$outtmp" "$ENV_LOCAL"; then
        ROUND_TRIP_VERIFIED=1
    else
        die "round-trip verification FAILED — $(basename "$ENV_AGE") does not decrypt back to $(basename "$ENV_LOCAL")"
    fi
elif [ -f "$IDENTITY" ]; then
    outtmp="$(mktemp)"
    trap 'rm -f "$outtmp"' EXIT
    if age -d -i "$IDENTITY" -o "$outtmp" "$ENV_AGE" 2>/dev/null && cmp -s "$outtmp" "$ENV_LOCAL"; then
        ROUND_TRIP_VERIFIED=1
    else
        die "round-trip verification FAILED — $(basename "$ENV_AGE") does not decrypt back to $(basename "$ENV_LOCAL")"
    fi
else
    log "round-trip verification skipped (no private key available)"
fi

if [ "$ROUND_TRIP_VERIFIED" = "1" ]; then
    log "round-trip verified: $(basename "$ENV_AGE") decrypts byte-for-byte to $(basename "$ENV_LOCAL")"
fi

log "done. $(basename "$ENV_AGE") is ready for the first deploy."
log "reminder: devops/secrets/age-identity.txt must live in a password manager"
log "and be deleted from disk — the encrypted copy is unrecoverable without it."
