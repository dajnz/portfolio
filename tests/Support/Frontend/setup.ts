import { addCollection } from '@iconify/vue';
import type { IconifyJSON } from '@iconify/types';
import customJson from '@/iconSubsets/custom.json';
import deviconJson from '@/iconSubsets/devicon.json';
import heroiconsJson from '@/iconSubsets/heroicons.json';
import lucideJson from '@/iconSubsets/lucide.json';
import simpleIconsJson from '@/iconSubsets/simple-icons.json';

// Registers the iconify collections for Iconify's `Icon` component the
// same way the app entries do (resources/js/app.ts / ssr.ts +
// iconRegistry.ts). Without registration @iconify/vue attempts a runtime
// fetch from the Iconify API, which happy-dom aborts at window teardown
// (AbortError noise). heroicons covers the base components; devicon
// covers TechSkillTag/TechSkillAutocomplete; simple-icons covers the
// contact brand-icon cells (the page's lazy registration races the first
// render, so the set is registered eagerly here); lucide covers the
// TextEditor's subscript/superscript subset; custom
// covers the hand-fed non-iconify glyphs (SVGs in resources/icons/
// custom, generated by scripts/build-custom-icons.mjs). The subsets are
// generated from the strict icon manifests by `npm run icons:build`
// (scripts/build-icon-subsets.mjs) — small enough to load as-is in tests.
addCollection(heroiconsJson as IconifyJSON);
addCollection(deviconJson as IconifyJSON);
addCollection(simpleIconsJson as IconifyJSON);
addCollection(lucideJson as IconifyJSON);
addCollection(customJson as IconifyJSON);
