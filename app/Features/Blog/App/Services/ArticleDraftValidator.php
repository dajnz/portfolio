<?php

declare(strict_types=1);

namespace App\Features\Blog\App\Services;

use App\Features\Blog\Domain\Exceptions\ArticleSlugOccupiedException;
use App\Features\Blog\Domain\Exceptions\RelatedArticleNotLinkableException;
use App\Features\Blog\Domain\RepositoryInterfaces\ArticleRepositoryInterface;

/**
 * The store/update draft checks that need the database (content-
 * management.md:441-452,687) — deliberately NOT in the form request
 * (requests are shape/format validation; persistence probes belong to
 * the app layer). Runs after the request rules pass, before the
 * aggregate is built:
 *
 * - a MANUAL slug override (A3: not the naive auto-generation, not the
 *   stored slug) must not collide with another article (soft-deleted
 *   included — B29; the auto-generated values are re-resolved with a
 *   collision suffix by {@see ArticleSlugService}, so they never reach
 *   this check);
 * - each submitted related-article id must target a published article
 *   (content-management.md:687) unless it is ALREADY linked to the
 *   article — links created while the target was published are
 *   preserved on re-save even after an unpublish (B230), and the
 *   article cannot link to itself.
 */
final class ArticleDraftValidator
{
    public function __construct(
        private readonly ArticleRepositoryInterface $repository,
        private readonly ArticleSlugService $slugs,
    ) {
    }

    public function assertSlugOverrideAvailable(
        string $submittedSlug,
        ?string $storedSlug,
        string $enTitle,
        ?int $ignoreId,
    ): void {
        if ($this->slugs->isAutoGenerated($submittedSlug, $storedSlug, $enTitle)) {
            return;
        }

        if (in_array($submittedSlug, $this->repository->takenSlugs($submittedSlug, $ignoreId), true)) {
            throw ArticleSlugOccupiedException::forSlug($submittedSlug);
        }
    }

    /**
     * @param  int[]  $relatedArticleIds
     */
    public function assertRelatedLinkable(int $articleId, array $relatedArticleIds): void
    {
        $linked = $this->repository->relatedIdsOf($articleId);

        foreach ($relatedArticleIds as $relatedId) {
            if ($relatedId === $articleId) {
                throw RelatedArticleNotLinkableException::forSelf($relatedId);
            }

            if (! in_array($relatedId, $linked, true)
                && ! in_array($relatedId, $this->repository->publishedIdsOf([$relatedId]), true)) {
                throw RelatedArticleNotLinkableException::forArticle($relatedId);
            }
        }
    }
}
