<?php

declare(strict_types=1);

namespace App\Features\Blog\Infra\Requests;

use App\Features\Shared\Infra\Services\ActiveLocaleService;
use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;

/**
 * `POST /admin/blog` / `PUT /admin/blog/{article}`
 * (content-management.md:675-688): the shared fields plus the
 * per-locale translatable ones. `title` (min 3), `short_description`
 * and `content` (min 50) are required per active locale. The slug
 * rules: kebab-case regex, max 200, unique across ALL articles incl.
 * trashed (soft-deleted entities occupy their slug, B29) with the
 * current article ignored on update — EXCEPT the auto-generated
 * value: a submitted slug equal to the naive generation of the EN
 * title (or to the stored slug on update) skips the uniqueness
 * rejection — the use case re-resolves it server-side with a numeric
 * collision suffix (A3, content-management.md:441-452). A manual
 * override that collides is rejected here.
 *
 * Nested arrays: `tags` (article-tag ids), `skill_tags` (skill ids
 * attached via `article_skill_pivot`) and `related_articles`
 * (published article ids — `exists:blog_articles,id,is_published,1`
 * plus the not-self rule on update, content-management.md:687). The
 * lead image is a RustFS path string (`nullable, string, max:255` —
 * the file checks are the upload endpoint's job,
 * content-management.md:798-811).
 */
final class StoreArticleRequest extends FormRequest
{
    public function __construct(
        private readonly ActiveLocaleService $locales,
    ) {
        parent::__construct();
    }

    /** @return array<string, mixed> */
    public function rules(): array
    {
        $rules = [
            'slug' => [
                'required',
                'string',
                'regex:/^[a-z0-9]+(?:-[a-z0-9]+)*$/',
                'max:200',
                function (string $attribute, mixed $value, callable $fail): void {
                    if ($this->isAutoGeneratedSlug((string) $value)) {
                        return;
                    }

                    $exists = DB::table('blog_articles')
                        ->where('slug', $value)
                        ->when(
                            $this->route('article') !== null,
                            fn ($query): mixed => $query->where('id', '!=', $this->route('article')),
                        )
                        ->exists();

                    if ($exists) {
                        $fail(__('validation.unique', [
                            'attribute' => $this->attributes()['slug'] ?? 'slug',
                        ]));
                    }
                },
            ],
            'lead_image' => ['nullable', 'string', 'max:255'],
            'is_featured' => ['nullable', 'boolean'],
            'is_published' => ['nullable', 'boolean'],
            'tags' => ['nullable', 'array'],
            'tags.*' => ['integer', 'exists:article_tags,id'],
            'skill_tags' => ['nullable', 'array'],
            'skill_tags.*' => ['integer', 'exists:skills,id'],
            'related_articles' => ['nullable', 'array'],
            'related_articles.*' => [
                'integer',
                \Illuminate\Validation\Rule::exists('blog_articles', 'id')->where('is_published', true),
            ],
        ];

        foreach ($this->activeLocales() as $locale) {
            $rules["title.$locale"] = ['required', 'string', 'min:3', 'max:200'];
            $rules["short_description.$locale"] = ['required', 'string', 'max:300'];
            $rules["content.$locale"] = ['required', 'string', 'min:50'];
            $rules["lead_image_alt.$locale"] = ['nullable', 'string', 'max:500'];
        }

        $articleId = $this->route('article');
        if ($articleId !== null) {
            // content-management.md:687 — an article cannot link to
            // itself (the `related_articles` CHECK constraint backs
            // it up at the DB level).
            $rules['related_articles.*'][] = 'not_in:'.$articleId;
        }

        return $rules;
    }

    /**
     * Friendly attribute names for the per-locale fields — the raw
     * `title.en` keys would otherwise leak into the validation
     * messages.
     *
     * @return array<string, string>
     */
    public function attributes(): array
    {
        $attributes = ['slug' => __('admin.blog.slug')];
        foreach ($this->activeLocales() as $locale) {
            $suffix = ' ['.strtoupper($locale).']';
            $attributes["title.$locale"] = __('admin.blog.title').$suffix;
            $attributes["short_description.$locale"] = __('admin.blog.short_description').$suffix;
            $attributes["content.$locale"] = __('admin.blog.content').$suffix;
            $attributes["lead_image_alt.$locale"] = __('admin.blog.alt_text').$suffix;
        }

        return $attributes;
    }

    /**
     * A3: the submitted slug is "auto-generated" when it equals the
     * naive generation of the EN title (the client regenerates the
     * slug on every EN-title save — content-management.md:431) or the
     * currently stored slug on update (the regeneration trigger).
     * Such values skip the uniqueness rejection — the use case
     * re-resolves them with a collision suffix.
     */
    private function isAutoGeneratedSlug(string $value): bool
    {
        $enTitle = $this->input('title.en');

        if (is_string($enTitle) && $value === Str::slug($enTitle)) {
            return true;
        }

        $articleId = $this->route('article');
        if ($articleId === null) {
            return false;
        }

        return $value === DB::table('blog_articles')->where('id', $articleId)->value('slug');
    }

    /**
     * @return string[]
     */
    private function activeLocales(): array
    {
        return $this->locales->activeLocales();
    }
}
