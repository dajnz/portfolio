<?php

declare(strict_types=1);

namespace App\Features\Blog\Infra\Requests;

use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Support\Facades\DB;

/**
 * `POST /api/tags` — the inline tag creation of the blog article form
 * (features/blog.yaml#TagRequest): the shared slug and the per-locale
 * `name` map with AT LEAST ONE locale (`minProperties: 1` — the
 * frontend posts the current locale only). The tag↔skill name
 * cross-check is the use case's repository probe (B130/B132),
 * surfacing a `name` validation error.
 */
final class StoreTagApiRequest extends FormRequest
{
    /** @return array<string, mixed> */
    public function rules(): array
    {
        return [
            'slug' => [
                'required',
                'string',
                'regex:/^[a-z0-9]+(?:-[a-z0-9]+)*$/',
                'max:100',
                function (string $attribute, mixed $value, callable $fail): void {
                    if ($this->isAutoGeneratedSlug((string) $value)) {
                        return;
                    }

                    $exists = DB::table('article_tags')
                        ->where('slug', $value)
                        ->exists();

                    if ($exists) {
                        $fail(__('validation.unique', [
                            'attribute' => $this->attributes()['slug'] ?? 'slug',
                        ]));
                    }
                },
            ],
            'name' => ['required', 'array', 'min:1'],
            'name.*' => ['string', 'max:100'],
        ];
    }

    /**
     * A3: a slug equal to the naive generation of the EN name skips
     * the uniqueness rejection (the use case re-resolves it with a
     * collision suffix).
     */
    private function isAutoGeneratedSlug(string $value): bool
    {
        $enName = $this->input('name.en');

        return is_string($enName) && $value === \Illuminate\Support\Str::slug($enName);
    }
}
