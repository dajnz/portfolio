<?php

declare(strict_types=1);

namespace App\Features\Projects\Infra\Requests;

use App\Features\Shared\Infra\Services\ActiveLocaleService;
use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;
use Illuminate\Validation\Rule;
use Illuminate\Validation\Validator;

/**
 * `POST /admin/projects` / `PUT /admin/projects/{project}`
 * (content-management.md:621-648): the shared fields plus the
 * per-locale translatable ones. `title` and `brief_description` are
 * required per active locale; the Markdown content fields are
 * optional. The slug rules: kebab-case regex, max 200, unique across
 * ALL projects incl. trashed (soft-deleted entities occupy their slug,
 * B29) with the current project ignored on update — EXCEPT the
 * auto-generated value: a submitted slug equal to the naive generation
 * of the EN title (or to the stored slug on update) skips the
 * uniqueness rejection — the use case re-resolves it server-side with
 * a numeric collision suffix (A3, content-management.md:441-452). A
 * manual override that collides is rejected here.
 *
 * Nested arrays: `screenshots` (RustFS `image` path, per-locale
 * `alt_text`/`title`/`description` maps — reconciled by id per A2) and
 * `detail_items` (engineering Iconify `icon` in the `set:name` format —
 * membership is constrained by the strict icon manifests and the
 * restricted picker, the format invariant lives in
 * `EngineeringDetailIcon`, per-locale `title`/`description` required
 * when the item exists). The tech-writeup reference must point to a
 * PUBLISHED article (content-management.md:648); the display-time
 * re-check happens in the public controller.
 */
final class StoreProjectRequest extends FormRequest
{
    public function __construct(
        private readonly ActiveLocaleService $locales,
    ) {
        parent::__construct();
    }

    /** @return array<string, mixed> */
    public function rules(): array
    {
        $rules = [
            'slug' => [
                'required',
                'string',
                'regex:/^[a-z0-9]+(?:-[a-z0-9]+)*$/',
                'max:200',
                function (string $attribute, mixed $value, callable $fail): void {
                    if ($this->isAutoGeneratedSlug((string) $value)) {
                        return;
                    }

                    $exists = DB::table('projects')
                        ->where('slug', $value)
                        ->when(
                            $this->route('project') !== null,
                            fn ($query): mixed => $query->where('id', '!=', $this->route('project')),
                        )
                        ->exists();

                    if ($exists) {
                        $fail(__('validation.unique', [
                            'attribute' => $this->attributes()['slug'] ?? 'slug',
                        ]));
                    }
                },
            ],
            'preview_image' => ['nullable', 'string', 'max:255'],
            'github_url' => ['nullable', 'string', 'url', 'max:500'],
            'live_demo_url' => ['nullable', 'string', 'url', 'max:500'],
            'is_featured' => ['nullable', 'boolean'],
            'featured_sort_order' => [
                'nullable',
                'integer',
                'min:0',
                'required_if:is_featured,true',
            ],
            'is_published' => ['nullable', 'boolean'],
            'tech_writeup_article_id' => [
                'nullable',
                'integer',
                Rule::exists('blog_articles', 'id')->where('is_published', true),
            ],
            'tech_tags' => ['nullable', 'array'],
            'tech_tags.*' => ['integer', 'exists:skills,id'],
            'screenshots' => ['nullable', 'array'],
            'screenshots.*.image' => ['required_with:screenshots', 'string', 'max:255'],
            'screenshots.*.alt_text.*' => ['nullable', 'string', 'max:500'],
            'screenshots.*.title.*' => ['nullable', 'string', 'max:200'],
            'screenshots.*.description.*' => ['nullable', 'string', 'max:500'],
            'detail_items' => ['nullable', 'array'],
            'detail_items.*.icon' => [
                'required_with:detail_items',
                'string',
                'max:100',
                'regex:/^[a-zA-Z0-9\-]+:[a-zA-Z0-9\-]+$/',
            ],
        ];

        foreach ($this->activeLocales() as $locale) {
            $rules["title.$locale"] = ['required', 'string', 'max:200'];
            $rules["brief_description.$locale"] = ['required', 'string', 'max:300'];
            $rules["full_description.$locale"] = ['nullable', 'string'];
            $rules["problem.$locale"] = ['nullable', 'string'];
            $rules["solution.$locale"] = ['nullable', 'string'];
            $rules["preview_image_alt.$locale"] = ['nullable', 'string', 'max:500'];
            $rules["detail_items.*.title.$locale"] = ['required_with:detail_items', 'string', 'max:200'];
            $rules["detail_items.*.description.$locale"] = ['required_with:detail_items', 'string', 'max:2000'];
        }

        return $rules;
    }

    /**
     * The Markdown trio (full description / problem / solution) is
     * all-empty or all-filled ACROSS locales, per field (user request
     * 2026-08-12): a field filled in one language must be filled in
     * every language — filling one translation and not another is
     * rejected. Runs as `after()` callbacks: a closure rule on the
     * nullable field would be skipped whenever the value is null (the
     * framework's nullable skip), and the empty-string values arrive
     * as null after ConvertEmptyStringsToNull.
     *
     * @return array<int, \Closure>
     */
    public function after(): array
    {
        $callbacks = [];

        foreach (['full_description', 'problem', 'solution'] as $field) {
            foreach ($this->activeLocales() as $locale) {
                $callbacks[] = function (Validator $validator) use ($field, $locale): void {
                    $filledElsewhere = collect($this->activeLocales())
                        ->contains(fn (string $other): bool => $this->fieldHasContent("$field.$other"));

                    if ($filledElsewhere && ! $this->fieldHasContent("$field.$locale")) {
                        $validator->errors()->add(
                            "$field.$locale",
                            __('validation.projects.markdown_field_incomplete'),
                        );
                    }
                };
            }
        }

        return $callbacks;
    }

    /**
     * The raw request value of a dotted key is a non-empty string —
     * the null normalization (ConvertEmptyStringsToNull) is treated as
     * "not filled".
     */
    private function fieldHasContent(string $key): bool
    {
        $value = $this->input($key);

        return is_string($value) && trim($value) !== '';
    }

    /**
     * Friendly attribute names for the per-locale fields — the raw
     * `title.en` keys would otherwise leak into the validation
     * messages.
     *
     * @return array<string, string>
     */
    public function attributes(): array
    {
        $attributes = [];
        foreach ($this->activeLocales() as $locale) {
            $suffix = ' ['.strtoupper($locale).']';
            $attributes["title.$locale"] = __('admin.projects.title').$suffix;
            $attributes["brief_description.$locale"] = __('admin.projects.brief_description').$suffix;
            $attributes["full_description.$locale"] = __('admin.projects.full_description').$suffix;
            $attributes["problem.$locale"] = __('admin.projects.problem').$suffix;
            $attributes["solution.$locale"] = __('admin.projects.solution').$suffix;
            $attributes["preview_image_alt.$locale"] = __('admin.alt_text').$suffix;
        }

        return $attributes;
    }

    /**
     * A3: the submitted slug is "auto-generated" when it equals the
     * naive generation of the EN title (the client regenerates the
     * slug on every EN-title save — content-management.md:431) or the
     * currently stored slug on update (the regeneration trigger).
     * Such values skip the uniqueness rejection — the use case
     * re-resolves them with a collision suffix.
     */
    private function isAutoGeneratedSlug(string $value): bool
    {
        $enTitle = $this->input('title.en');

        if (is_string($enTitle) && $value === Str::slug($enTitle)) {
            return true;
        }

        $projectId = $this->route('project');
        if ($projectId === null) {
            return false;
        }

        return $value === DB::table('projects')->where('id', $projectId)->value('slug');
    }

    /**
     * @return string[]
     */
    private function activeLocales(): array
    {
        return $this->locales->activeLocales();
    }
}
