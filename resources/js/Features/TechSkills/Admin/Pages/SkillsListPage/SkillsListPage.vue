<!-- SkillsListPage — the skills management page orchestrator: the sticky
     Create Group action, the sortable groups (each with its sortable skill
     rows and inline editors), the transient new-group editor, the empty
     state and the shared delete dialog. The CRUD/reorder/delete/escape state
     lives in the useSkill* composables; the groups list, the per-group skills
     list and both transient editors are sub-components. -->
<script setup lang="ts">
import { addCollection } from '@iconify/vue';
import { usePage } from '@inertiajs/vue3';
import AdminBaseButton from '@shared-admin/AdminBaseButton.vue';
import AdminEmptyState from '@shared-admin/AdminEmptyState.vue';
import AdminPageLayout from '@shared-admin/AdminPageLayout.vue';
import AdminStickyActionBar from '@shared-admin/AdminStickyActionBar.vue';
import ConfirmationDialog from '@shared-admin/ConfirmationDialog.vue';
import { useAdminMenu } from '@shared-cross/Composables/useAdminMenu';
import { useI18n } from '@shared-cross/Composables/useI18n';
import { localeOptionsFromCodes } from '@shared-cross/Utils/localeOptions';
import type { SkillGroupData } from '@techskills-admin/SkillGroupCard.vue';
import { computed, ref, watch } from 'vue';
import deviconJson from '@/iconSubsets/devicon.json';

import NewSkillGroupEditor from './NewSkillGroupEditor.vue';
import SkillGroupsList from './SkillGroupsList.vue';
import { useEditorExits } from './useEditorExits';
import { useEditorScroll } from './useEditorScroll';
import { useSkillDelete } from './useSkillDelete';
import { useSkillGroups } from './useSkillGroups';
import { useSkillItems } from './useSkillItems';
import { useSkillReorder } from './useSkillReorder';

const props = withDefaults(
    defineProps<{
        skillGroups?: SkillGroupData[];
        test_id?: string;
    }>(),
    {
        skillGroups: () => [],
        test_id: 'skills-list-page',
    },
);

const { t } = useI18n();
const { menuGroups } = useAdminMenu();
const page = usePage<{ locale?: string; supported_locales?: string[] }>();

// The skill rows render `devicon:*` icons — the collection is registered
// offline and SYNCHRONOUSLY at module scope (static import, race-free —
// the rows can never render before it lands, so no runtime calls to the
// Iconify API). The devicon subset (generated by `pnpm run icons:build`
// from the icon manifests) stays out of the app bundle: the static edge
// loads the shared icons chunk with this page only.
addCollection(deviconJson);

// The page's shared working copy of the groups (deep-copied skill rows —
// the live checkbox PUTs must not leak into the props) — the CRUD and
// reorder composables mutate it and the page reconciles it with the
// server re-renders.
const groups = ref<SkillGroupData[]>(
    props.skillGroups.map((group) => ({ ...group, skills: [...group.skills] })),
);

const { setGroupSkills, onSkillsDragEnd, persistSkillOrder, persistGroupOrder } = useSkillReorder(
    groups,
    () => props.skillGroups,
);

const {
    editingGroupId,
    editingGroupLocale,
    groupDraft,
    groupErrors,
    savingGroup,
    warnedGroupLocales,
    groupNameError,
    startCreateGroup,
    startEditGroupById,
    cancelGroupEdit,
    updateGroupDraft,
    saveNewGroup,
    saveGroup,
    moveGroup,
} = useSkillGroups(groups, persistGroupOrder);

const {
    editingSkill,
    skillDraft,
    newSkillDraft,
    skillErrors,
    savingSkill,
    proficiencyOptions,
    startAddSkill,
    startEditSkill,
    cancelSkillEdit,
    saveNewSkill,
    saveSkill,
    updateSkillField,
    updateNewSkillDraft,
    moveSkill,
} = useSkillItems(groups, persistSkillOrder);

const { deleteTarget, isDeleting, requestDelete, dismissDelete, confirmDelete } = useSkillDelete();

useEditorExits({
    editingGroupId,
    editingSkill,
    groupErrors,
    skillErrors,
    cancelGroupEdit,
    cancelSkillEdit,
    testId: props.test_id,
});

useEditorScroll({
    editingGroupId,
    editingSkill,
    testId: props.test_id,
});

// The per-locale editing tabs only offer the ACTIVE locales (the
// shared `supported_locales` prop — disabled locales are not editable).
const locales = computed(() => localeOptionsFromCodes(page.props?.supported_locales));

watch(
    () => props.skillGroups,
    (next) => {
        groups.value = next.map((group) => ({ ...group, skills: [...group.skills] }));

        // A server re-render (create/save success) closes the transient
        // editors; edits of existing rows are closed by their guarded
        // onSuccess handlers.
        if (editingGroupId.value === 'new') {
            editingGroupId.value = null;
        }

        if (editingSkill.value?.skillId === 'new') {
            editingSkill.value = null;
        }
    },
);

function updateNewGroupName(locale: string, value: string): void {
    updateGroupDraft('name', { ...groupDraft.names, [locale]: value });
}
</script>

<template>
  <AdminPageLayout
    :menu_groups="menuGroups()"
    :active_route="'/admin/skills'"
    :locale_props="{
      active_locale: page.props?.locale ?? 'en',
      supported_locales: localeOptionsFromCodes(page.props?.supported_locales),
    }"
    :data-testid="`${props.test_id}-layout`"
  >
    <section
      class="mx-auto max-w-4xl"
      :data-testid="props.test_id"
    >
      <h1 class="mb-6 text-2xl font-bold text-slate-900 dark:text-white">
        {{ t('admin.skills.title') }}
      </h1>

      <AdminStickyActionBar :test_id="`${props.test_id}-sticky-bar`">
        <AdminBaseButton
          variant="primary"
          icon="heroicons:plus"
          icon_position="left"
          :test_id="`${props.test_id}-add-group`"
          @click="startCreateGroup"
        >
          {{ t('admin.skills.add_group') }}
        </AdminBaseButton>
      </AdminStickyActionBar>

      <template v-if="groups.length > 0 || editingGroupId === 'new'">
        <SkillGroupsList
          v-model:groups="groups"
          :editing_group_id="editingGroupId"
          :group_draft_names="groupDraft.names"
          :group_draft_icon="groupDraft.icon"
          :group_errors="groupErrors"
          :saving_group="savingGroup"
          :editing_skill="editingSkill"
          :skill_draft="skillDraft"
          :new_skill_draft="newSkillDraft"
          :skill_errors="skillErrors"
          :saving_skill="savingSkill"
          :proficiency_options="proficiencyOptions"
          :test_id="props.test_id"
          @update-group="updateGroupDraft"
          @edit-group="startEditGroupById"
          @save-group="saveGroup"
          @cancel-group="cancelGroupEdit"
          @delete-group="(id) => requestDelete('group', id)"
          @move-group="moveGroup"
          @add-skill="startAddSkill"
          @update-skill="updateSkillField"
          @edit-skill="startEditSkill"
          @save-skill="saveSkill"
          @cancel-skill="cancelSkillEdit"
          @delete-skill="(id) => requestDelete('skill', id)"
          @move-skill="moveSkill"
          @update-skills="setGroupSkills"
          @skills-drag-end="onSkillsDragEnd"
          @group-drag-end="persistGroupOrder"
          @new-skill-update="updateNewSkillDraft"
          @new-skill-save="saveNewSkill"
          @new-skill-cancel="(groupId) => cancelSkillEdit(groupId, 'new')"
        />

        <!-- Inline new-group editor — rendered AFTER the list so the
             pending group sits where the saved one lands (appended at the
             bottom). -->
        <NewSkillGroupEditor
          v-if="editingGroupId === 'new'"
          :locale="editingGroupLocale"
          :names="groupDraft.names"
          :icon="groupDraft.icon"
          :error_name="groupNameError()"
          :warned_locales="warnedGroupLocales"
          :locales="locales"
          :saving="savingGroup"
          :test_id="props.test_id"
          @update:locale="(value) => (editingGroupLocale = value)"
          @update:name="updateNewGroupName"
          @update:icon="(value) => updateGroupDraft('icon', value)"
          @save="saveNewGroup"
          @cancel="cancelGroupEdit"
        />
      </template>

      <AdminEmptyState
        v-else
        mode="empty"
        :message="t('admin.skills.empty_state')"
        :action_label="t('admin.skills.create_first_group')"
        :test_id="`${props.test_id}-empty`"
        @action="startCreateGroup"
      />

      <ConfirmationDialog
        :model-value="deleteTarget !== null"
        :title="
          deleteTarget?.type === 'group'
            ? t('admin.skills.delete_group_confirm')
            : t('admin.skills.delete_skill_confirm')
        "
        :message="
          deleteTarget?.type === 'group'
            ? t('admin.skills.delete_group_message')
            : undefined
        "
        :confirm_label="t('common.delete')"
        :is_loading="isDeleting"
        :test_id="`${props.test_id}-delete-dialog`"
        @update:model-value="(open) => {
          if (!open) dismissDelete();
        }"
        @confirm="confirmDelete"
      />
    </section>
  </AdminPageLayout>
</template>
